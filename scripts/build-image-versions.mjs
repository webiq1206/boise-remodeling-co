/**
 * Writes shared/generated/imageHashes.json and shared/generated/imageVersions.ts.
 *
 * The image optimizer answers with a one-year Cache-Control and keys its own
 * cache by the image URL, so a photograph replaced under the same file name
 * keeps serving the old picture to anyone who has seen it. lib/imageLoader.ts
 * appends ?v=<hash> to the paths listed in imageVersions.ts, which makes a
 * replaced file a new URL.
 *
 * imageHashes.json remembers every file's content hash (it is never imported
 * by the app). A file whose content differs from the remembered hash has been
 * replaced: it joins imageVersions.ts and stays there, its value following the
 * file from then on. A file that was never replaced carries no version.
 *
 * Run after adding or replacing an image: npm run images:versions
 * Guard: tests/image-versions.test.ts (in prebuild).
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const HASHES = path.join(root, 'shared/generated/imageHashes.json');
const VERSIONS = path.join(root, 'shared/generated/imageVersions.ts');
const EXT = /\.(webp|jpe?g|png|avif|gif)$/i;

export function currentImageHashes() {
  const out = {};
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (EXT.test(entry.name)) {
        const rel = '/' + path.relative(path.join(root, 'public'), full).split(path.sep).join('/');
        out[rel] = createHash('sha256').update(fs.readFileSync(full)).digest('hex').slice(0, 10);
      }
    }
  };
  walk(path.join(root, 'public/images'));
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

export function readVersions() {
  if (!fs.existsSync(VERSIONS)) return {};
  const body = fs.readFileSync(VERSIONS, 'utf8');
  return Object.fromEntries([...body.matchAll(/^\s*"([^"]+)": "([0-9a-f]+)",$/gm)].map((m) => [m[1], m[2]]));
}

function main() {
  const hashes = currentImageHashes();
  const before = fs.existsSync(HASHES) ? JSON.parse(fs.readFileSync(HASHES, 'utf8')) : {};
  const versions = readVersions();
  // --seed <file>: paths (one per line) already replaced before this record began.
  const seedAt = process.argv.indexOf('--seed');
  const seeded = seedAt > -1 ? fs.readFileSync(process.argv[seedAt + 1], 'utf8').split('\n').filter(Boolean) : [];
  const next = {};
  for (const [file, hash] of Object.entries(hashes)) {
    const replaced = (before[file] && before[file] !== hash) || file in versions || seeded.includes(file);
    if (replaced) next[file] = hash.slice(0, 8);
  }
  fs.writeFileSync(HASHES, JSON.stringify(hashes, null, 1) + '\n');
  const lines = Object.entries(next).map(([file, v]) => `  ${JSON.stringify(file)}: ${JSON.stringify(v)},`);
  fs.writeFileSync(
    VERSIONS,
    `// Generated by scripts/build-image-versions.mjs. Do not edit by hand.\n` +
      `// Images replaced under the same file name, with the hash of their current content.\n` +
      `export const IMAGE_VERSIONS: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n};\n`,
  );
  console.log(`image versions: ${lines.length} replaced of ${Object.keys(hashes).length} images`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
